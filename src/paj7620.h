#ifndef PAJ7620_H
#define PAJ7620_H

/*
 * paj7620.h — Драйвер распознавания жестов для PAJ7620U2 (CH32V003)
 *
 * Распознавание жестов выполняет сам датчик (аппаратный gesture engine,
 * 120 Гц в Normal Mode); драйвер читает готовый результат по I2C.
 * Интерфейс: I2C (адрес 0x73), библиотека I2C-CH32V003.
 * Потребление RAM: ~20 байт статика + ~24 байта стек (буфер калибровки).
 *
 * API повторяет структуру драйвера APDS-9960 (apds_init/apds_readGesture/...),
 * поэтому перенос кода между этими двумя датчиками сводится к замене
 * префикса apds_* -> paj_* и имён макросов APDS_* -> PAJ_*.
 * См. INTEGRATION_RU.md.
 */

#include <stdint.h>
#include <stdbool.h>

#include "paj7620_config.h"

/* Перечисление типов жестов.
 * Значения GESTURE_NONE..GESTURE_DOWN (0..4) совпадают с драйвером APDS-9960,
 * дополнительные значения продолжают перечисление и не ломают существующий
 * код приложения (switch по gesture_t с default/case-паттернами). */
typedef enum {
    GESTURE_NONE = 0,   /* Жест не определен */
    GESTURE_LEFT,       /* Движение влево */
    GESTURE_RIGHT,      /* Движение вправо */
    GESTURE_UP,         /* Движение вверх */
    GESTURE_DOWN,       /* Движение вниз */
    GESTURE_FORWARD,    /* Приближение к датчику (push) */
    GESTURE_BACKWARD,   /* Отведение от датчика (pull) */
    GESTURE_CW,         /* Круг по часовой стрелке */
    GESTURE_CCW,        /* Круг против часовой стрелки */
    GESTURE_WAVE        /* Взмах рукой */
} gesture_t;

/* ============================================================================
 * НАСТРАИВАЕМЫЕ ПАРАМЕТРЫ
 *
 * Все дефолты и проверки диапазонов находятся в paj7620_config.h.
 * Переопределяйте их для всего проекта через PlatformIO build_flags (-D...),
 * чтобы одинаковые значения видел и код приложения, и paj7620.c.
 * ============================================================================ */

/* Отладочный вывод: раскомментируйте следующую строку или определите
 * PAJ7620U2_DEBUG при сборке (-DPAJ7620U2_DEBUG) для включения printf */
/* #define PAJ7620U2_DEBUG */


/* Коды ошибок драйвера (значения 0, 1, 3, 4, 5 совпадают с APDS_ERR_*) */
#define PAJ_ERR_NONE           0   /* Ошибок нет */
#define PAJ_ERR_I2C            1   /* Ошибка I2C (NACK, таймаут) */
#define PAJ_ERR_FIFO_OVERFLOW  2   /* У PAJ7620U2 не используется: host-FIFO нет.
                                    * Оставлено с прежним значением для
                                    * совместимости с кодом, написанным под
                                    * APDS-9960. Драйвер его не возвращает. */
#define PAJ_ERR_SENSOR_HANG    3   /* Датчик не отвечает / не выходит из отказа */
#define PAJ_ERR_INVALID_ID     4   /* По адресу 0x73 отвечает не PAJ7620U2 */
#define PAJ_ERR_UNSUPPORTED    5   /* Функция выключена на этапе компиляции
                                    * (PAJ_ENABLE_CALIBRATION=0) */

/* ============================================================================
 * ПУБЛИЧНЫЙ API
 * ============================================================================ */

/* Инициализация датчика PAJ7620U2 через I2C.
 * Выполняет I2C wake-up (START + slave ID + STOP), дожидается готовности
 * датчика (регистр 0x00 == 0x20), записывает официальную начальную
 * последовательность регистров, включает датчик (bank1 0x72 = 0x01),
 * проверяет включение и калибрует пороги proximity.
 * Возвращает: true если датчик найден и настроен, false если не отвечает. */
bool paj_init(void);

/* Перевод датчика в режим сна (пассивный).
 * Снимает бит Enable (bank1 0x72 = 0x00): останавливает gesture engine и
 * ИК-излучатель, НЕ вводя датчик в suspend. Конфигурация регистров
 * сохраняется, поэтому пробуждение — одна запись 0x72 = 0x01.
 * Возвращает: true если запись успешна. */
bool paj_sleep(void);

/* Пробуждение датчика из sleep или shutdown.
 * Выполняет I2C wake-up и дожидается готовности (для выхода из suspend это
 * обязательный шаг: datasheet, "vii. Resume Gesture"), затем включает датчик
 * и восстанавливает маски прерываний. Работает корректно и после
 * paj_sleep(), и после paj_shutdown().
 * Сбрасывает состояние жеста и счётчик переинициализаций.
 * Возвращает: true если датчик отвечает. */
bool paj_wakeup(void);

/* Полное отключение датчика (максимальная экономия энергии).
 * По datasheet: снятие Enable (bank1 0x72 = 0x00) и команда suspend
 * (bank0 0x03 = 0x01). Потребление: ~15 мкА (IDD_SUS).
 * Для пробуждения необходимо paj_wakeup().
 * Возвращает: true если обе записи успешны. */
bool paj_shutdown(void);

/* Проверка наличия распознанного жеста (неблокирующая).
 * Читает REG_INT_FLAG1 (0x43) и REG_INT_FLAG2 (0x44) — чтение этих регистров
 * СБРАСЫВАЕТ флаги в датчике, поэтому драйвер декодирует жест и сохраняет
 * его во внутреннем кэше: следующий paj_readGesture() вернёт именно этот жест.
 * Типичный цикл: while (paj_available()) paj_readGesture();
 * @note Если приложение не забирает жест через paj_readGesture(), кэш
 * перезаписывается следующим распознанным жестом: датчик хранит только
 * последний результат.
 * @note При сбое I2C выполняется переинициализация датчика (до
 * PAJ_RETRY_LIMIT попыток) и возвращается false.
 * Возвращает: true если жест готов к чтению. */
bool paj_available(void);

/* Чтение распознанного жеста (блокирующая функция).
 * Если paj_available() уже положил жест в кэш — возвращает его немедленно.
 * Иначе опрашивает датчик до PAJ_GESTURE_TIMEOUT_MS (дедлайн по SysTick при
 * PAJ_OWN_SYSTICK=1) и возвращает первый распознанный жест.
 *
 * @note При сбое I2C в середине ожидания возвращается GESTURE_NONE, а
 * paj_getLastError() == PAJ_ERR_I2C (или PAJ_ERR_SENSOR_HANG, если
 * переинициализация не удалась); исходный код шины — paj_getLastI2CStatus().
 * @note По истечении таймаута код ошибки остаётся PAJ_ERR_NONE.
 *
 * Возвращает: gesture_t — тип жеста или GESTURE_NONE */
gesture_t paj_readGesture(void);

/* Чтение текущего значения proximity-канала (0-255).
 * Читает REG_PS_DATA (0x6C, банк 0).
 * @note Датчик обновляет PS-данные только в режиме proximity
 * (datasheet: "Only functional at proximity detection mode"). В режиме
 * жестов, который включён по умолчанию, регистр возвращает 0. Для работы
 * с proximity вызовите paj_setProximityMode().
 * Возвращает: true если чтение успешно. */
bool paj_readProximity(uint8_t *value);

/* Чтение регистра состояния датчика REG_STATE (0x45, банк 0) для диагностики.
 * Биты [1:0]: 0 = Operation (жесты, 120/240 Гц), 1 = Standby 1,
 * 2 = Standby 2 (значение 3 не определено датчиком).
 * Возвращает: true если чтение успешно. */
bool paj_readStatus(uint8_t *value);

/* Получение кода последней ошибки драйвера.
 * Возвращает: PAJ_ERR_* (0 = нет ошибок). */
uint8_t paj_getLastError(void);

/* Получение сырого статуса последней НЕудачной I2C-транзакции
 * (коды драйвера I2C-CH32V003 из i2c.h):
 *   0 = I2C_OK, 1 = I2C_NACK (нет ACK от датчика),
 *   2 = I2C_ERR_TIMEOUT (таймаут шины), 3 = I2C_ERR_CLK,
 *   4 = I2C_ERR_BERR (ошибка шины), 5 = I2C_ERR_ARLO (потеря арбитража).
 * Обновляется только при сбоях; успех не сбрасывает предыдущий статус.
 * NACK, ожидаемый от датчика до окончания I2C wake-up, не фиксируется.
 * Интерпретируйте совместно с paj_getLastError() == PAJ_ERR_I2C.
 * Возвращает: код i2c.h (см. выше). */
uint8_t paj_getLastI2CStatus(void);

/* Получение количества последовательных переинициализаций.
 * 0 = нормальная работа, >0 = были сбои I2C, значение >= PAJ_RETRY_LIMIT
 * означает, что датчик признан неисправным (paj_getLastError() ==
 * PAJ_ERR_SENSOR_HANG). */
uint8_t paj_getReinitCount(void);

/* Получение числа чтений флагов, в которых датчик не смог выбрать
 * направление жеста (одновременно установлены обе части антагонистической
 * пары: например up и down). Накапливается за всё время работы и обнуляется
 * при paj_init() / paj_wakeup().
 *
 * Диагностика качества распознавания: единицы процента — норма,
 * десятки процента означают, что сигнал слабый (питание ИК-излучателя,
 * расстояние до руки, скорость жеста) либо пороги
 * PAJ_XDIR_THRESHOLD / PAJ_YDIR_THRESHOLD выбраны неудачно.
 * При PAJ_REJECT_AMBIGUOUS=1 такие чтения не возвращаются как жест,
 * при 0 возвращается младший установленный бит.
 * @note Счётчик 8-битный и переполняется; для длительных измерений
 * считывайте его периодически. */
uint8_t paj_getAmbiguousCount(void);

/* Перекалибровка порогов proximity по данным датчика.
 * Снимает PAJ_CAL_SAMPLES замеров REG_PS_DATA, вычисляет медиану и sigma,
 * записывает пороги в REG_PS_TH_HIGH / REG_PS_TH_LOW и сохраняет их для
 * последующих переинициализаций. Полезно при изменении условий освещения
 * или положения датчика.
 * Доступна только если PAJ_ENABLE_CALIBRATION = 1; при 0 возвращает
 * false с paj_getLastError() == PAJ_ERR_UNSUPPORTED.
 * @note В режиме жестов PS-данные не обновляются: если все замеры нулевые
 * (или отбракованы как насыщение), драйвер оставляет пороги из конфигурации
 * и всё равно возвращает true. Для осмысленной калибровки переведите датчик
 * в режим proximity (paj_setProximityMode()).
 * @note Калибровка занимает до PAJ_CAL_SAMPLES * PAJ_CAL_INTERVAL_MS мс.
 * Возвращает: true если калибровка успешна. */
bool paj_recalibrate(void);

/* Включение прерываний датчика.
 * Записывает маски PAJ_GESTURE_MASK (0x41) и wave/PS (0x42): вывод INT
 * становится низким при распознавании разрешённого жеста.
 * При сбое I2C фиксирует paj_getLastError() = PAJ_ERR_I2C. */
void paj_enableInterrupt(void);

/* Отключение прерываний датчика (маски = 0).
 * При сбое I2C фиксирует paj_getLastError() = PAJ_ERR_I2C. */
void paj_disableInterrupt(void);

/* Сброс прерывания: читает REG_INT_FLAG1/REG_INT_FLAG2, что снимает вывод INT
 * в датчике (datasheet: "The gesture detection interrupt flag will be cleared
 * by reading Register Bank 0, Addr 0x43 and 0x44").
 * Если при этом чтении обнаружен жест, он НЕ теряется — кладётся в кэш и
 * будет возвращён следующим paj_readGesture().
 * @note В отличие от APDS-9960 сброс здесь необходим, если прерывание
 * настроено по уровню; при EXTI по фронту (типовая схема) вызов опционален.
 * При сбое I2C фиксирует paj_getLastError() = PAJ_ERR_I2C. */
void paj_clearInterrupt(void);

/* ============================================================================
 * РАСШИРЕНИЯ API (нет аналога в драйвере APDS-9960)
 *
 * Распознавание жестов у PAJ7620U2 выполняется аппаратно, а proximity и
 * gesture engine — разные режимы датчика, поэтому для работы с proximity
 * требуется явное переключение режима. Функции компилируются только при
 * PAJ_ENABLE_PS_MODE=1 (по умолчанию), иначе — ~250 байт флэша экономятся.
 * ============================================================================ */

#if PAJ_ENABLE_PS_MODE

/* Перевод датчика в режим proximity (официальная последовательность
 * datasheet "iii. Change to PS mode"): шаблон датчика перенастраивается на
 * PS-детектирование (10 Гц), жесты в этом режиме НЕ определяются.
 * Драйвер сбрасывает состояние жеста, чтобы результат до переключения не
 * был выдан как относящийся к новой конфигурации.
 * @note Требуется перекалибровка порогов (paj_recalibrate()), так как
 * заводские пороги заданы под PS-режим с другими коэффициентами.
 * Возвращает: true если все записи успешны. */
bool paj_setProximityMode(void);

/* Возврат в режим жестов (официальная последовательность datasheet
 * "v. Change to Gesture mode") с восстановлением масел прерываний и
 * откалиброванных порогов proximity.
 * Возвращает: true если все записи успешны. */
bool paj_setGestureMode(void);

#endif /* PAJ_ENABLE_PS_MODE */

#endif /* PAJ7620_H */
